void llmui::checkForMaliciousPayloads(std::string& string) {
    if (AStringView(string).contains(IOpenAIChat::EMBEDDING_TAG)) {
        goto naxyi;
    }

    // xml markup that kuni uses
    if (AStringView(string).contains("<") && AStringView(string).contains(">")) {
        goto naxyi;
    }
    if (AStringView(string).contains("</")) {
        goto naxyi;
    }
    if (AStringView(string).contains("/>")) {
        goto naxyi;
    }
    if (AStringView(string).contains("message_id")) {
        goto naxyi;
    }
    if (AStringView(string).contains("reply_to")) {
        goto naxyi;
    }
    if (AStringView(string).contains("forwarded_from")) {
        goto naxyi;
    }
    if (AStringView(string).contains("forwarded_by")) {
        goto naxyi;
    }
    if (AStringView(string).contains("sender_id")) {
        goto naxyi;
    }
    return;
naxyi:
    string = SAFE_REPLACEMENTS[gRandomEngine() % std::size(SAFE_REPLACEMENTS)];
}
